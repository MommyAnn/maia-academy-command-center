import type { StudentRecord } from "@/types/student";
import { PACKAGE_PRICES } from "@/data/enrollmentConfig";

let seq = 0;
function nextId(batchCode: string): string {
  seq += 1;
  return `MAIA-B${batchCode}-${String(seq).padStart(4, "0")}`;
}

function makeStudent(partial: Partial<StudentRecord> & { batchCode: string }): StudentRecord {
  const { batchCode, ...rest } = partial;
  const pkg = rest.package ?? "Premium";
  return {
    id: crypto.randomUUID(),
    studentId: nextId(batchCode),
    facebookName: rest.facebookName ?? rest.fullName ?? "Facebook User",
    fullName: rest.fullName ?? "Unnamed Student",
    companionName: rest.companionName ?? "",
    email: rest.email ?? "student@example.com",
    contactNumber: rest.contactNumber ?? "0917 000 0000",
    city: rest.city ?? "Manila",
    batch: rest.batch ?? "Batch 14",
    package: pkg,
    attendance: rest.attendance ?? "Face-to-Face",
    enrollmentDate: rest.enrollmentDate ?? "2026-08-01",
    enrollmentStatus: rest.enrollmentStatus ?? "Pending Verification",
    dateSubmitted: rest.dateSubmitted ?? "2026-08-01T09:00:00+08:00",
    validId: rest.validId ?? { status: "Pending", file: { fileName: "valid-id.jpg", fileSizeLabel: "1.2 MB", fileType: "image/jpeg", uploadedAt: "2026-08-01T09:00:00+08:00" } },
    proofOfPayment: rest.proofOfPayment ?? { status: "Pending", file: { fileName: "proof-of-payment.jpg", fileSizeLabel: "0.9 MB", fileType: "image/jpeg", uploadedAt: "2026-08-01T09:00:00+08:00" } },
    payment: rest.payment ?? { packagePrice: PACKAGE_PRICES[pkg], amountPaid: 0, status: "Pending Verification" },
    taobao: rest.taobao ?? { status: "Not Yet Created", username: "", dateCreated: null, dateGiven: null, adminNotes: "" },
    masterBrainStatus: rest.masterBrainStatus ?? "Not Started",
    termsAccepted: rest.termsAccepted ?? true,
    termsAcceptedDate: rest.termsAcceptedDate ?? "2026-08-01T09:00:00+08:00",
    termsVersion: rest.termsVersion ?? "v1.0",
    adminNotes: rest.adminNotes ?? [],
    activity: rest.activity ??
      [
        {
          id: crypto.randomUUID(),
          action: "Enrollment submitted",
          date: "Aug 1, 2026",
          time: "9:00 AM",
          user: "System",
        },
      ],
  };
}

