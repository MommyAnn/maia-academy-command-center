import type { PackageAdjustment, PaymentTransaction, Expense } from "@/types/finance";
import { DEMO_STUDENTS } from "@/data/demoStudents";
import type { StudentRecord } from "@/types/student";

function findStudent(studentId: string): StudentRecord {
  const student = DEMO_STUDENTS.find((s) => s.studentId === studentId);
  if (!student) throw new Error(`Demo finance data references unknown student ${studentId}`);
  return student;
}

function txn(
  id: string,
  studentDisplayId: string,
  partial: Partial<PaymentTransaction> & { amount: number; date: string },
): PaymentTransaction {
  const student = findStudent(studentDisplayId);
  return {
    id,
    studentId: student.id,
    studentDisplayId: student.studentId,
    studentName: student.fullName,
    batch: student.batch,
    package: student.package,
    type: "Full Payment",
    method: "Bank Transfer",
    referenceNumber: "",
    status: "Verified",
    proof: {
      fileName: "proof-of-payment.jpg",
      fileSizeLabel: "0.9 MB",
      fileType: "image/jpeg",
      uploadedAt: partial.date,
    },
    notes: "",
    recordedBy: "Mommy Ann",
    verifiedBy: "Mommy Ann",
    verifiedAt: partial.date,
    rejectedReason: null,
    createdAt: partial.date,
    ...partial,
  };
}

